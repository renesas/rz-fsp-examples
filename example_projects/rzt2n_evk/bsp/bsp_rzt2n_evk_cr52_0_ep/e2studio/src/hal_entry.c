#define PI                 (3.14159265358979F)
#define RADIAN_45_DEGREE   (PI / 4)
#define RADIAN_60_DEGREE   (PI / 3)
#define RADIAN_90_DEGREE   (PI / 2)
#define RADIAN_135_DEGREE  ((3 * PI) / 4)

void handle_error(fsp_err_t err);
void user_uart_callback(uart_callback_args_t * p_args);
void SVC_Handler(void);

static void tfu_example(void);

uint8_t           g_out_of_band_received[TRANSFER_LENGTH];
uint32_t          g_out_of_band_index = 0;
volatile uint32_t g_transfer_complete = 0;
volatile uint32_t g_receive_complete  = 0;

static float sin_angle   = 0;
static float cos_angle   = 0;
static float arc_tangent = 0;
static float hypotenuse  = 0;

/*******************************************************************************************************************//**
 * main() is generated by the FSP Configuration editor and is used to generate threads if an RTOS is used.
 * This function is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    /* Enable interrupts. */
    __enable_irq();

    /* Open UART. */
    fsp_err_t err = R_SCI_UART_Open(&g_uart0_ctrl, &g_uart0_cfg);
    handle_error(err);

    APP_PRINT(BANNER_INFO,
              EP_VERSION,
              4, 2, 0);

    APP_PRINT("\r\nExample Project Overview\r\n");
    APP_PRINT("This example demonstrates TFU trigonometric and vector calculation functions.\r\n");

    printf("CR52 TFU Sample program\n");

    tfu_example();

    while (1)
    {
        /* Do nothing. */
    }
}

/*******************************************************************************************************************//**
 * @brief       Demonstrate TFU trigonometric and vector calculation functions.
 * @param[in]   None
 * @retval      None
 **********************************************************************************************************************/
static void tfu_example(void)
{
    float angle_rad = RADIAN_60_DEGREE;

    /* Calculate the sine value of an angle. */
    sin_angle = sinf(angle_rad);
    printf("sinf() arg : angle_rad = %010.9f\n", angle_rad);
    printf("sinf() res : sin_angle = %010.9f\n", sin_angle);

    /* Calculate the cosine value of an angle. */
    cos_angle = cosf(angle_rad);
    printf("cosf() arg : angle_rad = %010.9f\n", angle_rad);
    printf("cosf() res : cos_angle = %010.9f\n", cos_angle);

    /* Calculate the sine and cosine values of an angle. */
    sin_angle = 0;
    cos_angle = 0;
    angle_rad = RADIAN_90_DEGREE;
    sincosf(angle_rad, &sin_angle, &cos_angle);
    printf("sincosf() arg : angle_rad = %010.9f\n", angle_rad);
    printf("sincosf() res : sin_angle = %010.9f, cos_angle = %010.9f\n", sin_angle, cos_angle);

    /* Calculate the arc tangent for the given values. */
    float x_coordinate = RADIAN_135_DEGREE;
    float y_coordinate = RADIAN_45_DEGREE;

    arc_tangent = atan2f(x_coordinate, y_coordinate);
    if ((1) == (R_TFU0->TRGSTS_b.ERRF))
    {
        printf("atan2f() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n", x_coordinate, y_coordinate);
        printf("atan2f() res : Input error occurred\n");
    }
    else
    {
        printf("atan2f() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n", x_coordinate, y_coordinate);
        printf("atan2f() res : arc_tangent = %010.9f\n", arc_tangent);
    }

    /* Calculate the hypotenuse for the given values. */
    hypotenuse = hypotf(x_coordinate, y_coordinate);
    if ((1) == (R_TFU0->TRGSTS_b.ERRF))
    {
        printf("hypotf() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n", x_coordinate, y_coordinate);
        printf("hypotf() res : Input error occurred\n");
    }
    else
    {
        printf("hypotf() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n", x_coordinate, y_coordinate);
        printf("hypotf() res : hypotenuse = %010.9f\n", hypotenuse);
    }

    /* Calculate the arc tangent and hypotenuse for the given values. */
    arc_tangent = 0;
    hypotenuse  = 0;
    x_coordinate = RADIAN_60_DEGREE;
    y_coordinate = RADIAN_90_DEGREE;

    atan2hypotf(x_coordinate, y_coordinate, &arc_tangent, &hypotenuse);
    if ((1) == (R_TFU0->TRGSTS_b.ERRF))
    {
        printf("atan2hypotf() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n",
               x_coordinate,
               y_coordinate);
        printf("atan2hypotf() res : Input error occurred\n");
    }
    else
    {
        printf("atan2hypotf() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n",
               x_coordinate,
               y_coordinate);
        printf("atan2hypotf() res : arc_tangent = %010.9f, hypotenuse = %010.9f\n",
               arc_tangent,
               hypotenuse);
    }

    /* Set special input values to generate an input error and set the TRGSTS.ERRF flag. */
    arc_tangent = 0;
    hypotenuse  = 0;
    x_coordinate = 0;
    y_coordinate = 0;

    atan2hypotf(x_coordinate, y_coordinate, &arc_tangent, &hypotenuse);
    if ((1) == (R_TFU0->TRGSTS_b.ERRF))
    {
        printf("atan2hypotf() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n",
               x_coordinate,
               y_coordinate);
        printf("atan2hypotf() res : Input error occurred\n");
    }
    else
    {
        printf("atan2hypotf() arg : x_coordinate = %010.9f, y_coordinate = %010.9f\n",
               x_coordinate,
               y_coordinate);
        printf("atan2hypotf() res : arc_tangent = %010.9f, hypotenuse = %010.9f\n",
               arc_tangent,
               hypotenuse);
    }
}

