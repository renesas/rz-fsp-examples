#ifndef CBS_CONFIG_H_
#define CBS_CONFIG_H_

#include <stdint.h>
#include "hal_data.h"

/* Use case, selected at runtime from the console menu */
typedef enum e_cbs_use_case
{
    CBS_UC_PORT_TO_PORT  = 1,   /* External traffic enters from ETH1 */
    CBS_UC_CPU_GENERATED = 2,   /* Traffic is generated by the CPU */
} cbs_use_case_t;

/* Port 2 is the CPU / GWCA internal port. The source and destination ports must differ, since the
 * switch does not send a frame back out the port it came in on */
#define CBS_SOURCE_PORT                 (1U)
#define CBS_CPU_PORT                    (2U)
#define CBS_DESTINATION_PORT            (0U)

/* MAC table */
#define CBS_MAC_TABLE_ENABLE            (1)

/* Table sizing.
 * All 8 IPV queues are covered (2 active + 6 permanently-empty placeholder rows) --
 * independent of LAYER3_SWITCH_CFG_AVAILABLE_QUEUE_NUM, which governs the separate GWCA
 * descriptor-queue pool (TX/RX rings), not the fixed 8 IPV priority queues per port */
#define CBS_ROW_COUNT                   (8U)

/* CPU-generated frame TX (CBS_UC_CPU_GENERATED only) */
/* Ring depth for cbs_send_frames_burst() -- it fills this many descriptors before one
 * StartDescriptorQueue() call, letting GWCA auto-chain through them instead of one Start per
 * descriptor. Chosen by hardware measurement: a larger ring gave a choppy, sub-cap per-second
 * reading on the CBS-enabled Q1 mode ([6]) -- credit accumulated and released in large,
 * infrequent bursts -- while this value gave a smooth clamp. Must stay above 1 -- at 1 it
 * degenerates to one Start per descriptor, which caps the offered load far too low to
 * demonstrate either cap. Costs (CBS_TX_DESC_NUM x CBS_FRAME_SIZE_MAX) bytes of non-cached
 * RAM for s_tx_frame_buf -- trivial at this size. */
#define CBS_TX_DESC_NUM                 (4U)
#define CBS_FRAME_SIZE_MAX              (1514U)   /* Near-MTU -- larger frames make the
                                                    * bandwidth cap easier to see than
                                                    * minimum-size frames would */
/* Source MAC placed in generated frames -- this board's Port 0 MAC address
 * (CBS_DESTINATION_PORT, the port these frames actually egress from). */
#define CBS_TX_SOURCE_MAC               {0x00, 0x11, 0x22, 0x33, 0x44, 0x00}
#define CBS_TX_ETHERTYPE                (0x88B5U)   /* IEEE local experimental */

/* Bandwidth table */

/* One row per IPV queue. band_width_pct/max_burst_num are the values applied when CBS is
 * enabled -- cbs_ep.c substitutes an all-zero layer3_switch_cbs_cfg_t when the tester
 * picks "disabled" from the menu, so this table never needs a separate disabled variant. */
typedef struct st_cbs_row
{
    uint8_t queue;              /* 0..7, IPV queue index */
    uint8_t band_width_pct;     /* CBS bandwidth limit, percent of link speed (0-100) */
    uint8_t max_burst_num;      /* Max burst frame count. NOTE: the underlying driver's
                                  * credit-upper-limit register write is currently
                                  * unconditionally multiplied by 0, so this has no
                                  * observable effect on hardware yet. Still set correctly
                                  * per the documented field, in case a future driver
                                  * update honors it. */
    uint8_t mac[6];              /* All-zero = no MAC table entry */
    uint8_t source_port_mask;    /* Bitmask of ingress ports to steer this MAC from --
                                   * bit N set = accept from port N (only one bit is ever
                                   * set here, but kept as a mask for future flexibility) */
} cbs_row_t;

/* One table per use case -- both exist in the binary at once; cbs_example.c picks a
 * pointer to one of them at runtime based on the console menu selection. Same 2 active
 * queues / destination MACs / bandwidth split in both -- only source_port_mask differs. */
extern const cbs_row_t g_cbs_rows_uc1[CBS_ROW_COUNT];   /* Port-to-port */
extern const cbs_row_t g_cbs_rows_uc2[CBS_ROW_COUNT];   /* CPU-generated */

#endif /* CBS_CONFIG_H_ */
