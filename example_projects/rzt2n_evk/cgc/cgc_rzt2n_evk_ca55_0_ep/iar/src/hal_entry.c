/*******************************************************************************
 * Function Name: led_blink
 * Description  : Blink all available board LEDs for the specified loop count.
 * Arguments    : loop_count -
 *                    Number of LED toggle loops.
 * Return Value : None.
 ******************************************************************************/
static void led_blink(uint32_t loop_count)
{
    /* Get the board LED configuration. */
    bsp_leds_t leds = g_bsp_leds;

    /* Trap if this board has no LEDs. */
    if (0 == leds.led_count)
    {
        while (1)
        {
            /* There are no LEDs on this board. */
        }
    }

    /* Turn off all board LEDs. */
    for (uint32_t i = 0; i < leds.led_count; i++)
    {
        R_BSP_PinClear((bsp_io_region_t) leds.p_leds[i][1], (bsp_io_port_pin_t) leds.p_leds[i][0]);
    }

    for (uint32_t loop = 0; loop < loop_count; loop++)
    {
        /* Toggle all board LEDs. */
        for (uint32_t i = 0; i < leds.led_count; i++)
        {
            R_BSP_PinToggle((bsp_io_region_t) leds.p_leds[i][1], (bsp_io_port_pin_t) leds.p_leds[i][0]);
        }

        /* Software delay. */
        for (volatile uint32_t j = 0; j < TIMEOUT; j++)
        {
            /* Do nothing. */
        }
    }
}

