#define TSU_EXAMPLE_LOWER_LIMIT  (0)
#define TSU_EXAMPLE_UPPER_LIMIT  (50)

void handle_error(fsp_err_t err);
void user_uart_callback(uart_callback_args_t * p_args);
void user_tsu_callback(adc_callback_args_t * p_args);
void SVC_Handler(void);

static void tsu_temperature_example(void);

uint8_t           g_out_of_band_received[TRANSFER_LENGTH];
uint32_t          g_out_of_band_index = 0;
volatile uint32_t g_transfer_complete = 0;
volatile uint32_t g_receive_complete  = 0;
volatile uint32_t g_tsu_scan_complete = 0;

/*******************************************************************************************************************//**
 * main() is generated by the FSP Configuration editor and is used to generate threads if an RTOS is used.
 * This function is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    /* Enable interrupts. */
    __enable_irq();

    /* Open UART. */
    fsp_err_t err = R_SCI_UART_Open(&g_uart0_ctrl, &g_uart0_cfg);
    handle_error(err);

    APP_PRINT(BANNER_INFO,
              EP_VERSION,
              4, 2, 0);

    APP_PRINT("\r\nExample Project Overview\r\n");
    APP_PRINT("This example demonstrates temperature measurement using the Temperature Sensor Unit (TSU).\r\n");

    printf("CR52 TSU Sample program\n");

    tsu_temperature_example();

    while (1)
    {
        /* Do nothing. */
    }
}

/*******************************************************************************
 * Function Name: tsu_temperature_example
 * Description  : Measure the device temperature using the TSU module.
 * Arguments    : None.
 * Return Value : None.
 ******************************************************************************/
static void tsu_temperature_example(void)
{
    /* The following example calculates the temperature on an RZ device using the data provided in the section
     * "Preparation for Using the Temperature Sensor" of the RZ microprocessor manual.
     */
    fsp_err_t err = FSP_SUCCESS;

    /* Initialize the module. */
    err = R_TSU_B_Open(&g_tsu0_ctrl, &g_tsu0_cfg);
    printf("R_TSU_Open err = %x\n", err);

    /* Handle any errors. */
    handle_error(err);

    adc_status_t tsu_status;

    do
    {
        err = R_TSU_B_StatusGet(&g_tsu0_ctrl, &tsu_status);
        handle_error(err);
    } while (ADC_STATE_SCAN_IN_PROGRESS == tsu_status.state);

    /* Enable the temperature sensor and start scanning. */
    (void) R_TSU_B_ScanStart(&g_tsu0_ctrl);

    /* Wait for conversion to complete and read converted data. To ensure accuracy, averaging data obtained
     * continuously at least eight times is required.
     */

    /* Eight-times averaging is performed using the SOSR1.ADCT setting. */
    do
    {
        err = R_TSU_B_StatusGet(&g_tsu0_ctrl, &tsu_status);
        handle_error(err);
    } while (ADC_STATE_SCAN_IN_PROGRESS == tsu_status.state);

    while (1U != g_tsu_scan_complete)
    {
        /* Wait for the TSU scan to complete. */
    }

    uint16_t scrr_val = 0;

    /* Read converted data. */
    err = R_TSU_B_Read(&g_tsu0_ctrl, ADC_CHANNEL_TEMPERATURE, &scrr_val);
    printf("R_TSU_Read err = %x\n", err);
    handle_error(err);
    printf("scrr_val value = %d\n", scrr_val);

    /* Calculate the temperature. */
    float temperature_c = 0;
    err = R_TSU_B_CalculateTemperature(&g_tsu0_ctrl, scrr_val, &temperature_c);
    printf("R_TSU_CalculateTemperature err = %x\n", err);
    handle_error(err);
    printf("temperature_c value = %.2f\n", temperature_c);

    /* Stop the module. */
    err = R_TSU_B_Close(&g_tsu0_ctrl);
    printf("R_TSU_Close err = %x\n", err);
    handle_error(err);

    /* Break if the temperature is outside the expected range. */
    if ((temperature_c < TSU_EXAMPLE_LOWER_LIMIT) || (temperature_c > TSU_EXAMPLE_UPPER_LIMIT))
    {
        __BKPT(0);
    }
}

