/*******************************************************************************
 * Function Name: user_uart_callback
 * Description  : Handle UART events.
 * Arguments    : p_args -
 *                    Pointer to UART callback arguments.
 * Return Value : None.
 ******************************************************************************/
void user_uart_callback(uart_callback_args_t * p_args)
{
    /* Handle the UART event. */
    switch (p_args->event)
    {
        case UART_EVENT_RX_CHAR:
        {
            /* Store the next received character if there is space in the buffer. */
            if (sizeof(g_out_of_band_received) > g_out_of_band_index)
            {
                /* This example is configured for 7-bit or 8-bit data, so the received data fits in one byte. */
                g_out_of_band_received[g_out_of_band_index++] = (uint8_t) p_args->data;
            }

            break;
        }

        case UART_EVENT_RX_COMPLETE:
        {
            g_receive_complete = 1;
            break;
        }

        case UART_EVENT_TX_COMPLETE:
        {
            g_transfer_complete = 1;
            break;
        }

        default:
        {
            /* Do nothing. */
            break;
        }
    }
}

/*******************************************************************************
 * End of function user_uart_callback
 ******************************************************************************/

/*******************************************************************************
 * Function Name: user_tsu_callback
 * Description  : Set the TSU scan completion flag.
 * Arguments    : p_args -
 *                    Pointer to ADC callback arguments.
 * Return Value : None.
 ******************************************************************************/
void user_tsu_callback(adc_callback_args_t * p_args)
{
    if (ADC_EVENT_SCAN_COMPLETE == p_args->event)
    {
        g_tsu_scan_complete = 1U;
    }
}

