/***********************************************************************************************************************
 * Private global variables and functions
 **********************************************************************************************************************/
/* Key data used in OTFD. */
/* The inject key generated from the information in the otfd_key.c file is stored. */
/* In the sample, it corresponds to the following key. */
/* --- AES-128 --- */
/* plain : 4BF34EDDE418A23B4EA7F49744BD5073 */
/* --- AES-256 --- */
/* plain : FB3577D4E8F7251869DEEC618E04C1D1767E6A17975CEB93FC976E92CCC355F0 */
uint8_t g_qspi0_otfd_key[RSIP_BYTE_SIZE_WRAPPED_KEY_AES_256] = {0xFF};

/* IV (counter value) used in OTFD. */
/* The value is determined from the following values specified in SKMT. */
/* The sample uses the values listed. */
/* nonce   (128bit) = BF89F643B5849AA0F19502CBC0000000 */
/* destaddr (32bit) = 40011000 */
/* g_otfd_iv = {nonce[127:28], destaddr[31:4]} */
/* When changing the value, pay attention to the endianness. */
uint32_t g_qspi0_otfd_iv[] =
{
    0xBF89F643, 0xB5849AA0, 0xF19502CB, 0xC4001100,
};

/******************************************************************************
 * @fn generate_otfd_inject_key
 * @brief A inject key is generated from the key information of the C source
 *        generated by SKMT and stored in the key area on RAM.
 *
 * @retval FSP_SUCCESS(0)  Success
 * @retval Other than 0    Failure
 ******************************************************************************/
fsp_err_t generate_otfd_inject_key(void)
{
    fsp_err_t fsp_err = FSP_SUCCESS;
    rsip_wrapped_key_t wrap_key;
    wrap_key.type = RSIP_KEY_TYPE_INVALID;
    
    /* Set buffer for inject user key. */
    wrap_key.p_value = g_qspi0_otfd_key;
    
#if USE_KEY128 == CFG_OTFD_SAMPLE_USE_KEY
    wrap_key.type = RSIP_KEY_TYPE_AES_128;
#endif
    
#if USE_KEY256 == CFG_OTFD_SAMPLE_USE_KEY
    wrap_key.type = RSIP_KEY_TYPE_AES_256;
#endif
    
    fsp_err = R_RSIP_Open(&g_rsip_ctrl, &g_rsip_cfg);
    if (FSP_SUCCESS != fsp_err)
    {
        return fsp_err;
    }
    
    do
    {
        /* Generate inject key. */
        fsp_err = R_RSIP_InitialKeyWrap(&g_rsip_ctrl, g_encrypted_user_key_data.wufpk, g_encrypted_user_key_data.initial_vector,
                                        g_encrypted_user_key_data.encrypted_user_key, &wrap_key);
        
        if (FSP_SUCCESS != fsp_err)
        {
            break;
        }
        
    } while (0);
    
    R_RSIP_Close(&g_rsip_ctrl);
    
    return fsp_err;
}
