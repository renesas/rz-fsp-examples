/***********************************************************************************************************************
* Function Name: R_LED_LED1OFF
* Description  : This function performs the processing in the code
* Arguments    : void
* Return Value : none
***********************************************************************************************************************/
void R_LED_LED1OFF(void)
{
    g_ioport.p_api->pinWrite(g_ioport.p_ctrl, LED_PIN, BSP_IO_LEVEL_LOW);
}

/***********************************************************************************************************************
* Function Name: R_LED_LED1ON
* Description  : This function performs the processing in the code
* Arguments    : void
* Return Value : none
***********************************************************************************************************************/
void R_LED_LED1ON(void)
{
    g_ioport.p_api->pinWrite(g_ioport.p_ctrl, LED_PIN, BSP_IO_LEVEL_HIGH);
}

